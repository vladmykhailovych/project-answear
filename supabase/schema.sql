-- ---------- Товари ----------
create table if not exists public.products (
  id           bigint generated by default as identity primary key,
  category     text    not null check (category in ('women', 'men', 'kids')),
  brand        text    not null check (length(trim(brand)) > 0),
  name         text    not null check (length(trim(name)) > 0),
  price        integer not null check (price >= 0),          -- повні гривні
  image_url    text    not null,                             -- /images/x.jpg або URL зі Storage
  sort_order   integer not null default 0,                   -- менше число — вище в списку
  is_published boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create index if not exists products_category_sort_idx
  on public.products (category, sort_order, id);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at
  before update on public.products
  for each row execute function public.set_updated_at();

-- ---------- Адміни ----------
-- Таблиця без жодних політик: через API її не прочитати. Перевірка йде через is_admin().
create table if not exists public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade
);
alter table public.admins enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admins where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- ---------- RLS для товарів ----------
alter table public.products enable row level security;

-- Права на таблицю (без них RLS-політики не спрацьовують: "permission denied for table products").
grant usage on schema public to anon, authenticated;
grant select on public.products to anon;
grant select, insert, update, delete on public.products to authenticated;

drop policy if exists "products: read published" on public.products;
create policy "products: read published"
  on public.products for select
  to anon, authenticated
  using (is_published or (select public.is_admin()));

drop policy if exists "products: admin insert" on public.products;
create policy "products: admin insert"
  on public.products for insert
  to authenticated
  with check ((select public.is_admin()));

drop policy if exists "products: admin update" on public.products;
create policy "products: admin update"
  on public.products for update
  to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

drop policy if exists "products: admin delete" on public.products;
create policy "products: admin delete"
  on public.products for delete
  to authenticated
  using ((select public.is_admin()));

-- ---------- Сховище фото ----------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'product-images', 'product-images', true,
  5242880,  -- 5 MB
  array['image/jpeg', 'image/png', 'image/webp', 'image/avif']
)
on conflict (id) do update
  set public             = excluded.public,
      file_size_limit    = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

-- Читати публічний бакет за URL можна без політик; решту дозволяємо лише адмінам.
drop policy if exists "product-images: admin select" on storage.objects;
create policy "product-images: admin select"
  on storage.objects for select
  to authenticated
  using (bucket_id = 'product-images' and (select public.is_admin()));

drop policy if exists "product-images: admin insert" on storage.objects;
create policy "product-images: admin insert"
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'product-images' and (select public.is_admin()));

drop policy if exists "product-images: admin update" on storage.objects;
create policy "product-images: admin update"
  on storage.objects for update
  to authenticated
  using (bucket_id = 'product-images' and (select public.is_admin()))
  with check (bucket_id = 'product-images' and (select public.is_admin()));

drop policy if exists "product-images: admin delete" on storage.objects;
create policy "product-images: admin delete"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'product-images' and (select public.is_admin()));

